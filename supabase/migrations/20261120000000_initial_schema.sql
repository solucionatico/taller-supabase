-- ============================================================================
-- Migración inicial: Esquema de gestión de tareas personales (public.tasks)
-- Proyecto: Taller de Herramientas Gratuitas de Despliegue (Supabase + Vercel)
-- ============================================================================

-- 1. Creación idempotente de la tabla public.tasks
CREATE TABLE IF NOT EXISTS public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (char_length(trim(title)) > 0),
    description TEXT,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    user_id UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.tasks IS 'Tareas personales de cada usuario autenticado en Supabase Auth.';
COMMENT ON COLUMN public.tasks.user_id IS 'Propietario de la tarea. Toma por defecto auth.uid() del JWT activo.';

-- 2. Índices para optimizar las consultas filtradas y ordenadas por usuario
CREATE INDEX IF NOT EXISTS idx_tasks_user_id
    ON public.tasks (user_id);

CREATE INDEX IF NOT EXISTS idx_tasks_user_created_at
    ON public.tasks (user_id, created_at DESC);

-- 3. Habilitar Row Level Security (RLS) de forma obligatoria
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;

-- 4. Permisos a nivel de rol en PostgreSQL (sujetos siempre a las políticas RLS)
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.tasks TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- 5. Políticas RLS (idempotentes mediante DROP POLICY IF EXISTS)
-- Todas las políticas comprueban la identidad real mediante auth.uid()

-- 5.1. Consultar únicamente las tareas propias
DROP POLICY IF EXISTS "Users can view their own tasks" ON public.tasks;
CREATE POLICY "Users can view their own tasks"
    ON public.tasks
    FOR SELECT
    TO authenticated
    USING (auth.uid() = user_id);

-- 5.2. Crear tareas únicamente a nombre del propio usuario autenticado
DROP POLICY IF EXISTS "Users can create their own tasks" ON public.tasks;
CREATE POLICY "Users can create their own tasks"
    ON public.tasks
    FOR INSERT
    TO authenticated
    WITH CHECK (auth.uid() = user_id);

-- 5.3. Actualizar únicamente las tareas propias
DROP POLICY IF EXISTS "Users can update their own tasks" ON public.tasks;
CREATE POLICY "Users can update their own tasks"
    ON public.tasks
    FOR UPDATE
    TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- 5.4. Eliminar únicamente las tareas propias
DROP POLICY IF EXISTS "Users can delete their own tasks" ON public.tasks;
CREATE POLICY "Users can delete their own tasks"
    ON public.tasks
    FOR DELETE
    TO authenticated
    USING (auth.uid() = user_id);
